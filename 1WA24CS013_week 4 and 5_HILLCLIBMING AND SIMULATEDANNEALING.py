import random

def get_conflicts(state):
    n = len(state)
    conflicts = 0
    for i in range(n):
        for j in range(i + 1, n):
            if state[i] == state[j]:
                conflicts += 1
            elif abs(state[i] - state[j]) == abs(i - j):
                conflicts += 1
    return conflicts

def get_neighbors(state):
    neighbors = []
    n = len(state)
    for col in range(n):
        for row in range(n):
            if state[col] != row:
                neighbor = list(state)
                neighbor[col] = row
                neighbors.append(neighbor)
    return neighbors

def hill_climbing(n, max_restarts=100):
    for restart in range(max_restarts):
        current_state = [random.randint(0, n - 1) for _ in range(n)]
        current_conflicts = get_conflicts(current_state)

        while True:
            neighbors = get_neighbors(current_state)
            if not neighbors:
                break

            neighbor_conflicts = [(neighbor, get_conflicts(neighbor)) for neighbor in neighbors]
            best_neighbor, min_conflicts = min(neighbor_conflicts, key=lambda x: x[1])

            if min_conflicts >= current_conflicts:
                break

            current_state = best_neighbor
            current_conflicts = min_conflicts

        if current_conflicts == 0:
            print(f"Solution found after {restart} restarts!")
            return current_state

    print("Failed to find a solution within the maximum restarts.")
    return None

def display_board(state):
    if not state:
        return
    n = len(state)
    for r in range(n):
        row_str = " ".join("Q" if state[c] == r else "." for c in range(n))
        print(row_str)

N = 8
solution = hill_climbing(N)

if solution:
    print(f"Solution State (columns 0 to {N-1} row indices): {solution}")
    print("\nBoard Layout:")
    display_board(solution)
else:
    print("No solution found.")

import math

def simulated_annealing(n, initial_temp=100.0, cooling_rate=0.95, max_iterations=2000):
    """Solve the N-Queens problem using Simulated Annealing."""
    current_state = [random.randint(0, n - 1) for _ in range(n)]
    current_conflicts = get_conflicts(current_state)

    temp = initial_temp

    for i in range(max_iterations):
        if current_conflicts == 0:
            print(f"Solution found at iteration {i}!")
            return current_state


        temp *= cooling_rate
        if temp < 1e-6:
            break


        col = random.randint(0, n - 1)
        row = random.randint(0, n - 1)
        while row == current_state[col]:
            row = random.randint(0, n - 1)

        next_state = list(current_state)
        next_state[col] = row
        next_conflicts = get_conflicts(next_state)


        energy_diff = next_conflicts - current_conflicts


        if energy_diff < 0 or random.random() < math.exp(-energy_diff / temp):
            current_state = next_state
            current_conflicts = next_conflicts

    if current_conflicts == 0:
        return current_state
    else:
        print(f"Failed to find a solution. Final conflicts: {current_conflicts}")
        return None

N = 8
sa_solution = simulated_annealing(N, initial_temp=100.0, cooling_rate=0.995, max_iterations=5000)

if sa_solution:
    print(f"Solution State (columns 0 to {N-1} row indices): {sa_solution}")
    print("\nBoard Layout:")
    display_board(sa_solution)
else:
    print("No solution found during this run.")
